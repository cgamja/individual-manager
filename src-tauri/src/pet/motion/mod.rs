//! 모션 도메인 — **동작 하나가 파일 하나**다.
//!
//! 각 파일에 그 동작의 매 틱 물리 · 진입 · 퇴장 · **테스트**가 함께 있다.
//! `pet.rs` 한 파일이던 시절에는 얼음낚시를 고치려면 4600줄 안에서 상수·`match`
//! 팔·진입 확률·테스트를 스크롤로 찾아다녀야 했다. 테스트에 손으로 그어 둔
//! `// ── 얼음낚시 ──` 같은 구분선이 그 시절의 흔적이다 — 작성자는 이미
//! 도메인으로 생각하고 있었고 파일이 그걸 못 담고 있었다.
//!
//! **여기 없는 것 셋**은 의도다 — 전부 `super`(= `pet`)에 남는다:
//!
//! - `pick_next` — 다음에 뭘 할지 고르는 **추첨기**. 모든 도메인의 확률이 한 곳에
//!   모여 있어야 서로의 비중이 보인다. 흩으면 "얼음낚시가 얼마나 드문가"를
//!   답하려고 파일 일곱을 열게 된다.
//! - `enter`·`enter_idle`·`clamp` — 도메인 사이를 오가는 전이 프리미티브.
//! - 난수(`range`·`fraction`) — 시드를 소유하는 것은 `Pet` 자신이다.
//!
//! 튜닝 값도 여기 없다 — `pet/tuning.rs` 한 곳이다. 값을 만지러 갈 곳이
//! 도메인마다 갈라지면 "이 동작이 얼마나 자주 나오나"를 비교할 수 없다.
//!
//! # 가시성
//!
//! 도메인이 부모에게 여는 진입점은 `pub(in crate::pet)`이다 — `pet`과 그 자손만
//! 본다. `pub(super)`로는 부족한데, 여기서 `super`는 `pet`이 아니라 `motion`이라
//! 정작 부르는 쪽(`pet`의 상태머신)이 못 본다.
//!
//! `pub`인 것들(`start_fishing` 등)은 설정 창의 "동작 시켜보기"가 브릿지를 거쳐
//! 부른다. 인헨런트 메서드의 공개 범위는 모듈 경로와 무관하므로 여기 있어도
//! 그대로 닿는다.

