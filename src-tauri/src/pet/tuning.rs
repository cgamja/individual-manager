//! 펭귄 코어의 튜닝 값 — 속도·길이·확률·문턱.
//!
//! **값을 만지러 오는 곳이 여기 하나다.** 모션이 늘 때마다 상수가 늘고, 그게
//! 상태머신 본문과 섞여 있으면 "이 동작이 얼마나 자주 나오나"를 답하려고
//! 파일 전체를 스크롤하게 된다.
//!
//! 각 값의 **문서 주석이 근거다** — 실측치, 계산, 왜 그 값이 아니면 안 되는지.
//! 값만 옮기고 주석을 두고 오면 숫자 나열이 된다.
//!
//! `const _: () = assert!(...)` 불변식은 값들 사이의 관계를 컴파일 시각에 묶는다
//! (예: `SPRAWL_MIN_IMPACT > SPLAT_MIN_IMPACT`). 값을 고칠 때 등급이 조용히
//! 뒤집히는 것을 막는 장치라 값 옆에 함께 둔다.
//!
//! 가시성은 `pub(super)`가 상한이다 — `pet` 모듈과 그 자식만 본다.
//! `pub(crate)`로 열면 브릿지가 코어의 튜닝 값에 손댈 수 있게 되어
//! "무슨 동작·어디에는 Rust 코어, 어떻게 보이는지는 웹뷰"라는 경계
//! (PRINCIPLE 4)가 코드로 지켜지지 않는다. **예외는 `PET_SIZE` 하나** —
//! 브릿지가 창 크기를 계산하려고 재수출한다.

/// 펭귄 자체가 차지하는 한 변 (논리 px).
///
/// 브릿지가 아니라 **코어가 소유한다** — 어느 화면 위에 서 있는지를 정하는
/// 기준점이 이 값에서 나오기 때문이다. 남의 모듈에서 가져와 자기 판정에 쓰면
/// 그 모듈을 고칠 때 판정이 조용히 따라 바뀐다.
pub const PET_SIZE: f64 = 140.0;

/// 걷는 속도 (논리 px/초).
pub(super) const WALK_SPEED: f64 = 42.0;
/// 헤엄치는 속도 (논리 px/초). 걷기보다 빨라야 "떠서 이동한다"는 느낌이 난다.
pub(super) const SWIM_SPEED: f64 = 95.0;
/// 내려앉는 속도 (논리 px/초). **헤엄보다 빠르다** — 중력이 돕는 방향이라
/// 같은 속도로 내려오면 미끄러지듯 느리다.
///
/// **값의 근거는 공중에 떠 있는 시간이다.** 자유낙하를 내려앉기로 바꾸면 화면
/// 꼭대기에서 바닥까지 8.4초가 걸려 헤엄 점유가 27.8% → 42.5%로 뛴다. 착지를
/// 고치려던 변경이 "펭귄이 절반쯤 공중에 떠 있는 앱"을 만들면 안 된다.
///
/// 모든 헤엄이 내려앉던 때는 이 값으로도 37.1%였다. 지금은 대부분이 다시
/// 자유낙하로 빠져(`SWIM_FREEFALL_PERCENT`) **28.7%**다 — 내려앉기를 넣기 전
/// (27.8%)과 거의 같다. 이 값이 살아 있는 이유는 남은 10% 갈래 때문이고,
/// 그 갈래가 느려지면 다시 점유가 뛴다.
pub(super) const SWIM_DESCENT_SPEED: f64 = 210.0;
const _: () = assert!(SWIM_DESCENT_SPEED > SWIM_SPEED);
/// 헤엄이 끝날 때 **자유낙하로 빠지는** 비율(%). 나머지는 위 속도로 내려앉는다.
///
/// **되돌린 결정이다** (2026-09-01 사용자 지시). 바로 위 주석이 적어 둔 대로
/// 내려앉기는 저절로 생기는 철푸덕·널브러짐을 0으로 만들려고 넣었는데, 그러면서
/// **하늘에서 떨어지는 그림도 함께 사라졌다.** 대가는 재서 안다 — 이 값으로
/// 널브러짐 55회/h, 철푸덕 48회/h가 나오고 **그 전부가 헤엄 끝에서 온다**
/// (20시간 실측, `빈도_측정`).
///
/// **100이 아닌 것에 값이 있다.** 갈래가 하나 남아야 헤엄의 끝이 완전히 예측
/// 가능한 지점이 아니게 된다 (PRINCIPLE 1 — 재미의 반대말은 예측 가능함이다).
pub(super) const SWIM_FREEFALL_PERCENT: u64 = 90;
/// 낙하 가속도 (논리 px/초²).
pub(super) const GRAVITY: f64 = 900.0;
/// 벽·천장에 부딪혔을 때 남는 속도 비율. 1.0이면 영원히 튕긴다.
pub(super) const BOUNCE_DAMPING: f64 = 0.5;
/// 던진 것으로 볼 최소 속도 (논리 px/초). 이보다 느리면 그냥 떨어뜨린 것이다.
/// **세계 크기와 무관하게 고정한다** — 이 문턱은 "사용자가 튕겼는가"라는 손의
/// 의도에 대한 것이고, 화면이 넓다고 같은 손짓이 떨어뜨림으로 바뀌면 이상하다 (KTD1).
pub(super) const THROW_MIN_SPEED: f64 = 260.0;
/// 던지기 속도 상한 — 초당 **세계를 몇 번 가로지르는가**. 절대 px/s로 두면 좁은
/// 화면에서 눈 깜짝할 새 가로지르고 넓은 화면에서는 답답하다. 취향 상수라 여기서만 고친다.
///
/// 여기서 "세계"는 화면 폭이 아니라 **펭귄이 실제로 다닐 수 있는 가로 범위**다
/// ([`Bounds`]는 창 크기를 이미 빼 놓았다). 그래야 이 비율이 "1초에 세계를 0.9번
/// 가로지른다"는 뜻으로 문자 그대로 읽힌다.
pub(super) const THROW_MAX_WORLDS_PER_SEC: f64 = 0.9;
/// 세계 폭을 못 구했을 때 쓸 기준 폭. 모니터 조회에 실패하면 브릿지가 폭 0인 납작한
/// 경계를 주는데, 그대로 비례식에 넣으면 상한이 0이 되어 **모든 던지기가 조용히
/// 낙하로 바뀐다**. 그런 죽음을 만들지 않으려고 둔다.
pub(super) const FALLBACK_WORLD_WIDTH: f64 = 1_440.0;
/// 헤엄 목적지에 도착했다고 볼 거리.
pub(super) const ARRIVE_EPSILON: f64 = 6.0;
/// 한 step이 정산하는 최대 시간. 시스템 슬립 등으로 틱이 밀렸을 때
/// 펭귄이 화면을 가로질러 순간이동하지 않게 잘라낸다.
pub(super) const MAX_STEP_MS: u64 = 250;

pub(super) const TURN_MS: u64 = 250;
/// 벽에 닿았을 때 **돌아서지 않고 그대로 박아 굴러 넘어질** 확률(%).
///
/// 벽 도달 자체가 흔하지 않아서(걷기가 2.5~6초 단발이고 속도는 `WALK_SPEED`)
/// 이보다 낮으면 평생 못 보고, 높이면 벽이 곧 넘어지는 곳이 되어 `Turn`이 사라진다.
/// 취향 상수라 여기서만 고친다.
pub(super) const TUMBLE_AT_WALL_PERCENT: u64 = 30;
/// 굴러 넘어지는 데 걸리는 시간. 도는 것보다 확실히 길어야 갈래가 갈래로 읽힌다.
pub(super) const TUMBLE_MS: u64 = 1_100;
/// 벽에 박은 반동으로 굴러가기 시작하는 속도 (논리 px/초). 걷기보다 빨라야
/// "튕겨서 굴렀다"로 보인다. 남은 시간에 비례해 0까지 줄어드므로 실제 이동
/// 거리는 이 값의 절반 × `TUMBLE_MS`, 대략 자기 몸 크기 남짓이다.
pub(super) const TUMBLE_SPEED: f64 = 200.0;
/// 도는 것보다 짧으면 "박고 나자빠졌다"가 "잠깐 비틀했다"로 읽힌다.
const _: () = assert!(TUMBLE_MS > TURN_MS);
/// 싸가지 반응의 길이. 한 박자 확실히 보여야 킹받는다.
pub(super) const SASSY_MS: u64 = 900;
/// 킹받는 한마디가 떠 있는 시간.
pub(super) const SPEECH_MS: u64 = 3_200;
/// 한마디와 다음 한마디 사이 간격. 클릭과 무관하게 알아서 떠든다.
pub(super) const TAUNT_GAP_MS: (u64, u64) = (7_000, 18_000);
/// 방망이를 휘두르는 시간.
pub(super) const SWING_MS: u64 = 360;

/// 빽빽거리는 시간. 싸가지보다 **확실히 길어야** 한 박자 큰 반응으로 읽힌다 —
/// 뒤집히면 정면으로 화내는 쪽이 무시하는 쪽보다 짧아지는 꼴이라 컴파일 타임에 막는다.
pub(super) const SQUAWK_MS: u64 = 1_400;
const _: () = assert!(SQUAWK_MS > SASSY_MS);
/// 이만큼 연달아 맞으면 빽빽거린다.
///
/// 취향 상수라 여기서만 고친다. 낮추면 몇 번 툭 치는 것으로 터져 "작정하고
/// 때렸을 때의 반응"이 아니게 되고, 높이면 평생 못 본다.
/// **스물이면 초당 서너 번 두들겨 5~7초쯤** 걸린다 — 지나가다 몇 번 클릭한
/// 것으로는 절대 안 닿고, 손이 먼저 지칠 만큼도 아니다.
pub(super) const SQUAWK_WHACK_COUNT: u64 = 20;
/// 연타로 인정하는 클릭 사이 최대 간격.
///
/// **문턱과 함께 봐야 하는 값이다.** 스무 번을 채우는 동안 한 번이라도 이 간격을
/// 넘기면 카운터가 1로 되돌아가므로, 문턱이 높을수록 간격은 넉넉해야 한다.
/// 2초면 **초당 한 번씩만 때려도 끊기지 않는다** — 중간에 손이 멎어도 봐준다.
pub(super) const SQUAWK_GAP_MS: u64 = 2_000;

/// 착지 후 약이 올라 한마디 할 확률(%).
pub(super) const SASSY_AFTER_LAND_PERCENT: u64 = 70;
pub(super) const LAND_MS: u64 = 300;
/// 철푸덕은 착지보다 **길다** — 퍼진 상태를 한 박자 보여줘야 철푸덕이다.
pub(super) const SPLAT_MS: u64 = 850;
/// 널브러짐은 철푸덕보다 **더** 길다. 배를 깔고 퍼진 것과 아예 뻗은 것은 다르다.
pub(super) const SPRAWL_MS: u64 = 1_700;
/// 착지 강도가 커질수록 오래 누워 있어야 강도가 읽힌다. 뒤집히면 세게 박을수록
/// 빨리 일어나는 꼴이 되므로 컴파일 타임에 막는다.
const _: () = assert!(SPLAT_MS > LAND_MS);
const _: () = assert!(SPRAWL_MS > SPLAT_MS);

/// 이 속도(논리 px/초) 이상으로 바닥에 닿으면 철푸덕한다.
///
/// 중력이 900px/s²이므로 대략 **270px 넘게 떨어졌을 때**다. 제자리에서 놓거나
/// 한 뼘 떨어진 것으로 배를 깔면 착지가 매번 요란해진다.
pub(super) const SPLAT_MIN_IMPACT: f64 = 700.0;
/// 이 속도 이상이면 아예 **널브러진다**. 대략 550px 넘게 떨어졌거나 아래로
/// 내리꽂았을 때다 — 화면 위쪽에서 떨어뜨리면 닿는 값이어야 의미가 있다.
pub(super) const SPRAWL_MIN_IMPACT: f64 = 1_000.0;
const _: () = assert!(SPRAWL_MIN_IMPACT > SPLAT_MIN_IMPACT);

/// 이 속도보다 느리게 닿으면 튀지 않고 그대로 선다. 없으면 0에 수렴할 때까지
/// 영원히 잔진동한다.
pub(super) const BOUNCE_MIN_SPEED: f64 = 150.0;
/// 바닥에서 튈 때 남는 속도 비율. 벽(`BOUNCE_DAMPING`)보다 많이 죽인다 —
/// 바닥은 몇 번 통통거리다 서야지, 오래 튀면 공처럼 보인다.
pub(super) const FLOOR_BOUNCE_DAMPING: f64 = 0.45;
/// **핀볼 모드**에서 벽·천장·바닥이 전부 쓰는 반사 계수. 위 둘을 한 값으로
/// 대체한다 — 핀볼에서 벽은 범퍼고, 취향 조정이 한 곳에 있어야 한다.
///
/// **값의 근거는 랠리 길이다.** 500px 높이에서 떨어지면 착지 속도가 949px/s이고,
/// `BOUNCE_MIN_SPEED` 아래로 죽기까지 이 값으로 **22번** 튄다 (0.9면 17번,
/// 0.95면 35번). **1.0으로 두면 안 된다** — 영원히 튀어서 펭귄이 다시는 걷지
/// 않고 20Hz 틱이 영영 안 쉰다.
pub(super) const PINBALL_DAMPING: f64 = 0.92;
/// **핀볼 모드에서 채로 쳤을 때의 속도** — 초당 세계를 몇 번 가로지르는가.
/// 던지기 상한(`THROW_MAX_WORLDS_PER_SEC`)과 같은 근거다: 절대 px/s로 두면
/// 좁은 화면에서 눈 깜짝할 새 가로지르고 넓은 화면에서는 답답하다.
///
/// **0.55로 시작했다가 0.8로 올렸다** (2026-09-01, 써 보고). 계산상으로는
/// 던지기보다 얌전한 게 맞아 보였는데, 실제로 쳐 보니 랠리가 안 살았다 —
/// 핀볼은 공이 빨라야 판이 굴러간다.
///
/// 던지기 상한(0.9)은 넘지 않는다. 채로 한 번 치는 것이 팔로 힘껏 뿌리는 것보다
/// 세면 던지기가 무의미해진다 — 아래 단언이 그 선을 지킨다.
pub(super) const PINBALL_HIT_WORLDS_PER_SEC: f64 = 0.8;
const _: () = assert!(PINBALL_HIT_WORLDS_PER_SEC < THROW_MAX_WORLDS_PER_SEC);
const _: () = assert!(PINBALL_DAMPING < 1.0);
const _: () = assert!(PINBALL_DAMPING > BOUNCE_DAMPING);
/// 마지막 자극(클릭·드래그) 이후 이만큼 지나면 졸기로 넘어간다.
/// 길게 잡는다 — 펭귄이 깨어서 돌아다니는 게 이 기능의 목적이고, 졸기는 양념이다.
pub(super) const SLEEP_AFTER_MS: u64 = 300_000;

pub(super) const WALK_MS: (u64, u64) = (2_500, 6_000);
pub(super) const IDLE_MS: (u64, u64) = (1_200, 3_200);
/// 졸기는 끝이 있다 — 깨어나 다시 움직인다. 종착 상태가 아니다.
pub(super) const SLEEP_MS: (u64, u64) = (12_000, 25_000);
/// 유휴가 끝났을 때 다시 걸을 확률(%). 멈춰 있는 시간보다 걷는 시간이 길어야 한다.
pub(super) const WALK_AGAIN_PERCENT: u64 = 72;
/// 동작이 끝났을 때 공중으로 떠오를 확률(%).
pub(super) const SWIM_PERCENT: u64 = 30;

/// 미끄러지는 한 판의 길이. **고정이다** — 거리는 출발 속도로 흔든다.
///
/// 길이를 뽑으면 CSS 애니메이션 길이를 이 값과 맞출 수 없다
/// (`pet-css.test.ts`의 "동작 길이 동기화"가 대조하는 것이 고정 상수다).
pub(super) const SLIDE_MS: u64 = 2_400;

/// 배를 깔고 출발하는 속도 범위 (논리 px/초). 여기서 뽑아 감속한다 —
/// 거리는 `속도 × 길이 / 2`라 매번 다르다 (264~408px).
///
/// **하한은 취향이 아니라 계산이다.** 가장 느리게 출발해도 가장 오래 걸은 것
/// (`WALK_SPEED × WALK_MS.1` = 252px)보다 멀리 가야 "걷기보다 멀리"가 조건 없이
/// 참이 된다. 180으로 뒀더니 216px이라 긴 걷기에 졌다.
pub(super) const SLIDE_SPEED: (f64, f64) = (220.0, 340.0);

/// **걷기가** 끝났을 때 미끄러질 확률(%).
///
/// 유휴 뒤에는 나오지 않는다 — 서 있다가 갑자기 배를 깔면 준비 동작이 없다.
/// 걷던 관성이 있어야 미끄러지는 것으로 읽힌다.
pub(super) const SLIDE_AFTER_WALK_PERCENT: u64 = 20;

// 회전이 다 돌기도 전에 미끄러짐이 끝나면 자세가 튄다
const _: () = assert!(SLIDE_MS > TURN_MS);

/// **N번에 한 번** 발작한다. `range((0, N-1)) == 0`이 문자 그대로 그 뜻이다.
///
/// 천분율(얼음낚시)로는 이 등급을 표현할 수 없고, 백만분율은 값을 읽어도 빈도를
/// 가늠할 수 없다.
///
/// **실측 기준 `pick_next`는 6.8초마다 불린다** — 30,000 사이클 = 깨어 있는
/// **약 57시간**이고, 하루 열 시간쯤 켜 둔다면 **엿새에 한 번꼴**이다
/// (`MOTIONS.md` 빈도 표의 "며칠에 한 번. 봤으면 운이 좋은 것").
/// 처음에는 한 사이클을 4초로 잡아 33시간으로 적었는데, 그 4초가 틀렸다.
pub(super) const FREAKOUT_ONE_IN: u64 = 30_000;
/// 한 판의 예산. 이 시간이 지나면 바닥으로 돌아가 숨을 고른다.
pub(super) const FREAKOUT_MS: (u64, u64) = (2_000, 4_000);
/// 바닥에서 숨을 고르는 시간. **고정이다** — CSS 길이와 대조한다.
pub(super) const FREAKOUT_PANT_MS: u64 = 700;
/// 튀어 다니는 속도 (논리 px/초).
///
/// **틱이 그릴 수 있는 속도여야 한다.** 창은 보간 없이 50ms마다 한 번 옮겨지므로
/// (`pet_bridge`의 `TICK_MS`) 이 값을 20으로 나눈 것이 **한 프레임에 뛰는 거리**다 —
/// 480이면 24px이고, 지금까지 가장 빠른 슬라이딩(340 → 17px)보다 반 뼘 크다.
/// 900으로 잡았다가 45px이 되어 펭귄 몸통(140px)의 3분의 1씩 순간이동했다.
/// 어차피 광란으로 읽히게 하는 건 속도가 아니라 **방향이 바뀌는 빈도**다.
pub(super) const FREAKOUT_SPEED: f64 = 480.0;
/// 다음 목적지까지의 거리 (논리 px).
///
/// **멀리 두지 않는 것이 핵심이다.** 속도와 함께 봐야 하는 값이다 — 이 거리면
/// 0.2~0.46초마다 방향이 바뀌어 한 판에 네댓 번에서 스무 번까지 꺾인다.
/// 속도를 낮추면서 같이 줄였다. 안 줄이면 한 번 뛰는 데 0.7초가 걸려
/// "마구 튄다"가 "천천히 헤맨다"가 된다.
pub(super) const FREAKOUT_HOP: (f64, f64) = (100.0, 220.0);

// 광란이 헤엄보다 느리면 광란이 아니다
const _: () = assert!(FREAKOUT_SPEED > SWIM_SPEED);
